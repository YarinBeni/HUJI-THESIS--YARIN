"""W3: collect every probe JSON into the money tables + RESULTS.md.

Outputs (committed):
  results/summary_best_layer_r2.csv        rows = method(+site), cols = datasets
  results/summary_best_layer_spearman.csv
  results/summary_layerwise.csv            long format, one row per probe layer
  results/RESULTS.md                       markdown tables incl. the paper row
"""
import glob
import json
import os
import sys

import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from wm_lib.entity_data import ENTITY_TYPES  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
RESULTS_DIR = os.path.join(HERE, "results")

# display order: paper anchor first, then trained arms big->small, randoms, floor
METHOD_ORDER = [
    "llama2_70b", "llama2_13b", "llama2_7b", "olmo2_7b",
    "gpt_oss_120b", "qwen3_32b", "qwen3_8b", "qwen3_1b7",
    "umt5_base", "thalesian_cunei400m", "thalesian_akk300m",
    "llama2_70b_random", "llama2_13b_random", "llama2_7b_random",
    "olmo2_7b_random", "random",
    "tfidf",
]


def load_all():
    rows = []
    for path in glob.glob(os.path.join(RESULTS_DIR, "probes", "*", "*.json")):
        with open(path) as f:
            r = json.load(f)
        for li, sc in r["layers"].items():
            t = sc["test"]
            # ordering metric, comparable across domains: time -> spearman; geo ->
            # mean of the latitude and longitude rank correlations (not just lat)
            if "spearman" in t:
                sp = t["spearman"]
            else:
                sp = (t.get("lat_spearman", float("nan"))
                      + t.get("lon_spearman", float("nan"))) / 2
            rows.append({
                "method": r["method"], "entity_type": r["entity_type"],
                "site": r["site"], "probe": r["probe"], "layer": int(li),
                "test_r2": t["r2"],
                "test_spearman": sp,
                "train_r2": sc["train"]["r2"],
                "is_best": int(li) == r["best_layer"],
            })
    return pd.DataFrame(rows)


def canonical_site(df):
    """One row per method x entity_type: causal->last, encoder->mean, tfidf->text."""
    enc = {"umt5_base", "thalesian_cunei400m", "thalesian_akk300m"}

    def _rank(r):
        prefer = ("mean" if r["method"] in enc
                  else "text" if r["method"] == "tfidf" else "last")
        return 0 if r["site"] == prefer else 1

    df = df.copy()
    df["site_rank"] = df.apply(_rank, axis=1)
    df = df.sort_values(["method", "entity_type", "site_rank"])
    return df.groupby(["method", "entity_type"], as_index=False).first()


def pivot(best, col):
    t = best.pivot(index="method", columns="entity_type", values=col)
    t = t.reindex([m for m in METHOD_ORDER if m in t.index])
    return t[[c for c in ENTITY_TYPES if c in t.columns]]


def main():
    df = load_all()
    if df.empty:
        print("no probe results found yet")
        return
    df.to_csv(os.path.join(RESULTS_DIR, "summary_layerwise.csv"), index=False)

    best = canonical_site(df[df.is_best].drop(columns="is_best"))
    r2 = pivot(best, "test_r2")
    sp = pivot(best, "test_spearman")
    r2.round(3).to_csv(os.path.join(RESULTS_DIR, "summary_best_layer_r2.csv"))
    sp.round(3).to_csv(os.path.join(RESULTS_DIR, "summary_best_layer_spearman.csv"))

    with open(os.path.join(HERE, "paper_reference.json")) as f:
        ref = json.load(f)
    ref_row = pd.Series(ref["best_test_r2"], name=ref["model"])
    r2_disp = pd.concat([ref_row.to_frame().T, r2])

    lines = [
        "# W results — space & time probes, our ladder vs Gurnee & Tegmark",
        "",
        "Best-layer held-out **test R²** (canonical site: last for causal, mean for "
        "encoders; empty prompt; their is_test split). Paper row = reported "
        "Llama-2-70B numbers.",
        "",
        r2_disp.round(3).to_markdown(),
        "",
        "Best-layer test Spearman (places: mean of latitude & longitude axes):",
        "",
        sp.round(3).to_markdown(),
        "",
        "Generated by aggregate_results.py; layer curves in summary_layerwise.csv, "
        "figures in results/figs/.",
    ]
    with open(os.path.join(RESULTS_DIR, "RESULTS.md"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print(r2_disp.round(3).to_string())
    print(f"\nwrote {RESULTS_DIR}/RESULTS.md")


if __name__ == "__main__":
    main()
